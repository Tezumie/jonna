// Writes THIRD_PARTY_NOTICES.md: every production dependency the app ships, with its license.
// npm packages come with their license text; Rust crates are listed with their license and
// where to find them (their texts are in each crate's own repository).
// Run with: npm run notices   (after adding or updating a dependency)
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// ---- npm (production only, direct and transitive)
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const tree = JSON.parse(
  execFileSync(npm, ["ls", "--omit=dev", "--all", "--json", "--long"], {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
    maxBuffer: 64 * 1024 * 1024,
  }),
);
const packages = new Map();
(function visit(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (packages.has(key) || !info.path || !existsSync(info.path)) continue;
    const pkg = JSON.parse(readFileSync(join(info.path, "package.json"), "utf8"));
    const license =
      typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "UNKNOWN");
    const file = readdirSync(info.path).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
    const repo =
      typeof pkg.repository === "string"
        ? pkg.repository
        : (pkg.repository?.url ?? pkg.homepage ?? "");
    packages.set(key, {
      license,
      repo: repo.replace(/^git\+/, "").replace(/\.git$/, ""),
      text: file ? readFileSync(join(info.path, file), "utf8").replace(/\r\n/g, "\n").trim() : "",
    });
    visit(info.dependencies);
  }
})(tree.dependencies);

// ---- Rust crates (everything in Cargo.lock except this workspace's own crates)
let crates = [];
try {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: join(root, "src-tauri"),
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  const own = new Set(meta.workspace_members);
  crates = meta.packages
    .filter((p) => !own.has(p.id) && p.source)
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? "see repository",
      repo: p.repository ?? "",
    }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
} catch (e) {
  console.error(`cargo metadata failed, Rust crates left out: ${e.message.split("\n")[0]}`);
  process.exitCode = 1;
}

// ---- write
const out = [
  "# Third-party notices",
  "",
  "This file is generated by `npm run notices`. Don't edit it by hand.",
  "",
  "Jonna includes or links the third-party software below. Each keeps its own license, shown",
  "here. Jonna's own license is in [LICENSE](LICENSE).",
  "",
  `## npm packages (${packages.size})`,
  "",
];
for (const [key, p] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  out.push(`### ${key}`, "", `License: ${p.license}${p.repo ? `  \nSource: ${p.repo}` : ""}`, "");
  if (p.text) out.push("```", p.text.replace(/```/g, "'''"), "```", "");
}
out.push(
  `## Rust crates (${crates.length})`,
  "",
  "Each crate's license text is in its repository.",
  "",
  "| Crate | Version | License | Source |",
  "|---|---|---|---|",
  ...crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} | ${c.repo} |`),
  "",
  "## Other bundled software",
  "",
  "- **OpenConsole / ConPTY** (Microsoft, MIT): `src-tauri/conpty/x64/LICENSE.txt`.",
  "- **notify** (vendored, CC0-1.0): `src-tauri/vendor/notify/LICENSE-CC0`.",
  "- **Provider and agent logos**: `src/assets/brands/` (see its `SOURCES.md` and license file).",
  "",
);
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
console.log(`THIRD_PARTY_NOTICES.md: ${packages.size} npm packages, ${crates.length} Rust crates.`);
