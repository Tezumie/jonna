// The model providers the AI models page offers as tiles (D164, D212): the hosted and local
// servers people use most, spoken to through the OpenAI-compatible API (Anthropic through its own).
// Featured ones are always shown; the rest come with "View more". Each base URL is the provider's
// documented OpenAI-compatible endpoint. DOM-free: the page, the commands and the matching
// (providerMatch.ts) read it.

export interface ProviderPreset {
  id: string;
  name: string;
  /** The API's base; empty when it's the user's own (an Azure resource): `editAddress` then. */
  baseUrl: string;
  needsKey: boolean;
  /** Where to get a key (shown as a link; host and path, no scheme). */
  keyHint?: string;
  keyPlaceholder?: string;
  kind?: "anthropic";
  /** The model to start with when this provider is added and none is chosen yet. */
  defaultModel?: string;
  /** One line on the tile. */
  blurb?: string;
  /** Short labels on the tile ("Free models", "Local"). */
  tags?: string[];
  /** On the first rows of tiles (the common choices); the others under "View more". */
  featured?: boolean;
  /** The tile's badge without a logo: a letter or two in the provider's color (D167). */
  mark: string;
  /** Logo file (src/assets/brands/<brand>.svg) and color token suffix (`--brand-<brand>`). */
  brand: string;
  /** Other names people type for it ("groqcloud", "kimi"): the name box's suggestions (D212). */
  aliases?: string[];
  /** Hosts that are this provider (a subdomain counts): a hand-added one gets its logo (D212). */
  hosts?: string[];
  /** Its address differs per account or region: the form asks for it along with the key. */
  editAddress?: boolean;
  addressPlaceholder?: string;
}

